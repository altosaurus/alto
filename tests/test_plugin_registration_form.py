"""
Exercise the registration issue template and the approval workflow's
registry writer.
"""

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest
import yaml
from scripts.register_plugin import FORM, issue_entry

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = yaml.safe_load((ROOT / FORM).read_text(encoding="utf-8"))
ATTESTATION = TEMPLATE["body"][-1]["attributes"]["options"][0]["label"]
BODY = f"""### Plugin name

Viola Studio

### Description

Practice naming notes on all four strings.

### GitHub repository

https://github.com/example/strings

### Pack ID

viola-studio

### Metadata URL

_No response_

### Rights and licenses

- [x] {ATTESTATION}"""


@pytest.mark.parametrize(
    ("body", "error"),
    [
        (BODY.replace("- [x]", "- [ ]"), "Rights and licenses"),
        (BODY.replace(ATTESTATION, "I read the form."), "Rights and licenses"),
        (BODY.replace("viola-studio", "_No response_"), "Pack ID"),
        (BODY + "\n### Pack ID\nother", "Duplicate"),
        (
            BODY.replace(
                "https://github.com/example/strings",
                "https://example.net/strings",
            ),
            "GitHub repository",
        ),
        (
            BODY.replace("_No response_", "http://example.org/info.json"),
            "HTTPS URL",
        ),
    ],
)
def test_incomplete_registration(body: str, error: str) -> None:
    """
    Refuse incomplete or ambiguous answers and require the exact checked
    attestation.

    Parameters
    ----------
    body : str
        Markdown generated by the form or subsequently edited.
    error : str
        Text identifying the field needing correction.
    """
    with pytest.raises(ValueError, match=error):
        issue_entry({"number": 247, "body": body}, form=TEMPLATE)


def test_approval_creates_registry_entry(tmp_path: Path) -> None:
    """
    Run the approval script on an issue event, repeat it, and check
    conflict handling.

    Parameters
    ----------
    tmp_path : Path
        Isolated checkout containing a form and an empty registry.
    """
    assert TEMPLATE["body"][-1]["attributes"]["options"][0]["required"] is True
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    subprocess.run(
        [
            "git",
            "-c",
            "user.name=Test",
            "-c",
            "user.email=test@example.org",
            "commit",
            "-q",
            "--allow-empty",
            "-m",
            "initial",
        ],
        cwd=tmp_path,
        check=True,
    )
    form = tmp_path / FORM
    form.parent.mkdir(parents=True)
    form.write_bytes((ROOT / FORM).read_bytes())
    registry = tmp_path / "docs/site-root/plugins.json"
    registry.parent.mkdir(parents=True)
    registry.write_text("[]\n", encoding="utf-8")
    event = tmp_path / "event.json"
    data = {"number": 247, "body": BODY.replace("\n", "\r\n")}
    event.write_text(json.dumps({"issue": data}), encoding="utf-8")
    command = [sys.executable, "-m", "scripts.register_plugin", str(event)]
    env = os.environ | {"PYTHONPATH": str(ROOT)}
    for _ in range(2):
        subprocess.run(command, cwd=tmp_path, env=env, check=True)
        assert json.loads(registry.read_bytes()) == [
            {
                "id": "viola-studio",
                "code": "247",
                "name": "Viola Studio",
                "description": "Practice naming notes on all four strings.",
                "repository": "https://github.com/example/strings",
            },
        ]
    original = registry.read_bytes()
    event.write_text(
        json.dumps({"issue": data | {"number": 248}}),
        encoding="utf-8",
    )
    result = subprocess.run(
        command,
        cwd=tmp_path,
        env=env,
        capture_output=True,
        text=True,
    )
    assert result.returncode != 0 and "already registered" in result.stderr
    assert registry.read_bytes() == original


def test_optional_metadata() -> None:
    """
    Keep an explicit author metadata URL and accept a blank optional
    field.
    """
    address = "https://example.org/plugin.json"
    entry = issue_entry(
        {"number": 248, "body": BODY.replace("_No response_", address)},
        form=TEMPLATE,
    )
    assert entry["metadata"] == address
    assert "metadata" not in issue_entry(
        {
            "number": 248,
            "body": BODY.replace("### Metadata URL\n\n_No response_", ""),
        },
        form=TEMPLATE,
    )
