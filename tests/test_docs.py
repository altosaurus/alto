"""
The docs and their screenshots stay in step.

Every picture a page shows exists in both themes, and each one can be
regenerated with scripts/screenshots.py.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from types import ModuleType

import base64
import importlib.util
import re
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
IMG = ROOT / "docs" / "assets" / "img"


def script() -> ModuleType:
    """
    Load scripts/screenshots.py as a module, without running it.

    Returns
    -------
    ModuleType
        The loaded module.
    """
    spec = importlib.util.spec_from_file_location("screenshots", ROOT / "scripts" / "screenshots.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)  # only defines things; the work happens under __main__
    return module


def shown() -> set[str]:
    """
    Return the picture names the docs pages include with shot.html, without the .png.

    Returns
    -------
    set of str
        The pictures the docs pages include.
    """
    found = set()
    for page in (ROOT / "docs").glob("*.md"):
        found |= set(re.findall(r'shot\.html src="([^"]+)\.png"', page.read_text()))
    return found


def test_every_picture_a_page_shows_exists_in_both_themes() -> None:
    """
    Check that every picture a page shows exists in both themes.
    """
    assert shown()
    for name in shown():
        assert (IMG / f"{name}.png").is_file(), f"{name}.png is missing"
        assert (IMG / f"{name}-dark.png").is_file(), f"{name}-dark.png is missing"


def test_every_picture_can_be_regenerated_by_the_script() -> None:
    """
    Check that every picture can be regenerated by the script.
    """
    made = set(script().SHOTS)
    assert shown() == made, "docs pictures and scripts/screenshots.py disagree"


def test_no_picture_of_the_exercise_level_settings_is_made_or_kept() -> None:
    """
    Check that no picture of the exercise level settings is made or kept.
    """
    # The pane behind the sliders button is described in text, never shown (see CLAUDE.md).
    assert not [p.name for p in IMG.glob("*exercise-settings*")]
    assert not [n for n in script().SHOTS if "exercise-settings" in n]
    assert ".gear" not in (ROOT / "scripts" / "screenshots.py").read_text()


def test_the_python_versions_in_the_readme_badge_are_the_ones_the_tests_run_on() -> None:
    """
    Check that the python versions in the readme badge are the ones the tests run on.
    """
    workflow = (ROOT / ".github" / "workflows" / "tests.yml").read_text()
    matrix = re.search(r"python-version:\s*\[([^]]*)]", workflow)
    assert matrix is not None
    tested = re.findall(r'"([\d.]+)"', matrix.group(1))
    badge = re.search(r"img\.shields\.io/badge/python-([^)]*?)-\w+(?:\?[^)]*)?\)", (ROOT / "README.md").read_text())
    assert badge is not None, "the README has no Python versions badge"
    assert unquote(badge.group(1)).split(" | ") == tested
    # and the oldest of them is what pyproject.toml asks for
    minimum = re.search(r'requires-python\s*=\s*">=([\d.]+)"', (ROOT / "pyproject.toml").read_text())
    assert minimum is not None and minimum.group(1) == tested[0]


def test_the_readme_badges_that_name_a_tool_carry_its_logo_as_a_small_embedded_picture() -> None:
    """
    Check the six badges with a logo: each names a real workflow (or the Python versions) and carries its picture in its address.

    Shields has a one-colour pytest and Python logo of its own, but the colour ones, and the pictures for Pyright,
    ASV and Jekyll, are not in its set. So each picture is carried in the badge's address. They must stay small,
    so that the address does, and be PNG files.
    """
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    for label, workflow in (
        ("Tests", "tests.yml"),
        ("Ruff", "ruff.yml"),
        ("Pyright", "pyright.yml"),
        ("ASV", "performance.yml"),
        ("Docs", "docs.yml"),
    ):
        found = re.search(rf"\[!\[{label}]\((https://img\.shields\.io/[^)]+)\)]\(([^)]+)\)", readme)
        assert found is not None, f"the README has no {label} badge"
        badge, link = found.groups()
        assert f"/{workflow}?" in badge and (ROOT / ".github" / "workflows" / workflow).is_file()
        assert f"/actions/workflows/{workflow}" in link or label == "Docs"
    for label in ("Tests", "Ruff", "Pyright", "ASV", "Docs", "Python"):
        badge = re.search(rf"\[!\[{label}]\((https://img\.shields\.io/[^)]+)\)]", readme)
        assert badge is not None, f"the README has no {label} badge"
        logo = re.search(r"[?&]logo=([^&)\s]+)", badge.group(1))
        assert logo is not None, f"the {label} badge has no logo"
        image = unquote(logo.group(1))
        assert image.startswith("data:image/png;base64,")
        data = base64.b64decode(image.split(",", 1)[1])
        assert data.startswith(b"\x89PNG\r\n\x1a\n") and len(data) < 2000
        assert len(logo.group(1)) < 2000  # the whole address stays short enough for GitHub to fetch it


def test_the_ruff_workflow_runs_the_version_of_the_pre_commit_hook_on_every_change() -> None:
    """Check that the Ruff workflow pins the hook's version, checks the formatting and the rules, and runs on pull requests."""
    workflow = (ROOT / ".github" / "workflows" / "ruff.yml").read_text(encoding="utf-8")
    hook = re.search(
        r"astral-sh/ruff-pre-commit\s+rev: v([0-9.]+)",
        (ROOT / ".pre-commit-config.yaml").read_text(encoding="utf-8"),
    )
    assert hook is not None
    assert f'pip install "ruff=={hook.group(1)}"' in workflow  # the hook and the workflow hold the code to the same rules
    assert "ruff format --check ." in workflow and "ruff check ." in workflow
    assert "pull_request:" in workflow and "branches: [main]" in workflow
